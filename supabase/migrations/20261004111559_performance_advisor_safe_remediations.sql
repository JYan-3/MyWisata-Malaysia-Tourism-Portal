  TO authenticated
  USING (
    (
      ((review_status)::text = 'approved'::text)
      AND EXISTS (
        SELECT 1 FROM customer_voucher_claims claims
        WHERE claims.voucher_id = vouchers.id
          AND claims.user_id = (SELECT auth.uid())
