    OR (
      is_active = true
      AND (review_status)::text = 'approved'::text
    )
  );

-- Normalize auth/current_setting expressions in place. ALTER POLICY leaves each
-- policy's command and role set unchanged; each original predicate remains.
DO $performance_advisor_initplan$
DECLARE
  p record;
  v_using text;
  v_check text;
  v_statement text;
BEGIN
  FOR p IN
    SELECT schemaname, tablename, policyname, qual, with_check
    FROM pg_policies
    WHERE schemaname = 'public'
      AND (
        coalesce(qual, '') ~* 'auth\.[a-z_]+\s*\('
        OR coalesce(with_check, '') ~* 'auth\.[a-z_]+\s*\('
        OR coalesce(qual, '') ~* 'current_setting\s*\('
        OR coalesce(with_check, '') ~* 'current_setting\s*\('
      )
  LOOP
    v_using := p.qual;
    v_check := p.with_check;

    IF v_using IS NOT NULL THEN
      v_using := regexp_replace(
        v_using,
        'auth\.([a-z_]+)\s*\(\s*\)',
        '(SELECT auth.\1())',
        'gi'
      );
      v_using := regexp_replace(
        v_using,
        'current_setting\s*\(([^()]*)\)',
        '(SELECT current_setting(\1))',
        'gi'
      );
    END IF;

    IF v_check IS NOT NULL THEN
      v_check := regexp_replace(
        v_check,
        'auth\.([a-z_]+)\s*\(\s*\)',
        '(SELECT auth.\1())',
        'gi'
      );
      v_check := regexp_replace(
        v_check,
        'current_setting\s*\(([^()]*)\)',
        '(SELECT current_setting(\1))',
        'gi'
      );
    END IF;

    v_statement := format(
      'ALTER POLICY %I ON %I.%I',
      p.policyname,
      p.schemaname,
      p.tablename
    );
    IF v_using IS NOT NULL THEN
      v_statement := v_statement || format(' USING (%s)', v_using);
    END IF;
    IF v_check IS NOT NULL THEN
      v_statement := v_statement || format(' WITH CHECK (%s)', v_check);
    END IF;

    EXECUTE v_statement;
  END LOOP;
END
$performance_advisor_initplan$;

RESET lock_timeout;
