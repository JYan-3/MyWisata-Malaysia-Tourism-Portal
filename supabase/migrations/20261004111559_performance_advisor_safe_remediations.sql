-- existing visibility of offers outside that public predicate.
ALTER POLICY outlet_offers_public_read ON public.outlet_offers
  USING (
    (
      ((status)::text = 'active'::text)
      AND EXISTS (
        SELECT 1 FROM products p
        WHERE p.id = outlet_offers.product_id
          AND (p.status)::text = 'active'::text
          AND (p.review_status)::text = 'approved'::text
      )
      AND EXISTS (
        SELECT 1 FROM outlets o
        WHERE o.id = outlet_offers.outlet_id
          AND (o.status)::text = 'active'::text
      )
    )
    OR EXISTS (
      SELECT 1 FROM outlet_managers m
      WHERE m.outlet_id = outlet_offers.outlet_id
        AND m.user_id = (SELECT auth.uid())
    )
    OR EXISTS (
      SELECT 1 FROM outlets o
      JOIN vendors v ON v.id = o.vendor_id
      WHERE o.id = outlet_offers.outlet_id
        AND v.owner_id = (SELECT auth.uid())
    )
  );
